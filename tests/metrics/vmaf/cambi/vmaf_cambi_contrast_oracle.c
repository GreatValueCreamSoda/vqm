// /tmp/vmaf-cambi-contrast-oracle 17 >> tests/metrics/vmaf/cambi/vmaf_cambi_contrast_reference.inc
// /tmp/vmaf-cambi-contrast-oracle 33 > tests/metrics/vmaf/cambi/vmaf_cambi_contrast_reference33.inc
// clang-format on
#include "../../../../build/vmaf-src/libvmaf/src/feature/cambi.c"
#include <inttypes.h>
#include <stdlib.h>

int main(int argc, char** argv) {
    unsigned window = argc > 1 ? (unsigned)strtoul(argv[1], NULL, 10) : 11;
    if (window != 11 && window != 17 && window != 33) return 1;
    const unsigned w = window == 33 ? 65 : 31;
    const unsigned h = window == 33 ? 49 : 29, n = w * h;
    const uint16_t bases[] = {76, 177, 304, 558};
    uint16_t *image = calloc(n, sizeof(*image)),
             *mask = calloc(n, sizeof(*mask));
    uint16_t* mode_scratch = calloc(3 * w, sizeof(*mode_scratch));
    float* values = calloc(n, sizeof(*values));
    VmafPicture picture = {0}, mask_pic = {0};
    picture.w[0] = mask_pic.w[0] = w;
    picture.h[0] = mask_pic.h[0] = h;
    picture.stride[0] = mask_pic.stride[0] = w * 2;
    picture.data[0] = image;
    mask_pic.data[0] = mask;
    for (unsigned y = 0; y < h; ++y)
        for (unsigned x = 0; x < w; ++x) {
            image[y * w + x] = bases[(x / 8) % 4] + ((x / 2 + y / 3) % 5);
            mask[y * w + x] = (x / 7 + y / 6) % 7 != 0;
        }
    filter_mode(&picture, w, h, mode_scratch);
    uint64_t hash = UINT64_C(14695981039346656037);
    for (unsigned i = 0; i < n; i++)
        hash = (hash ^ image[i]) * UINT64_C(1099511628211);
    VmafLumaRange range;
    VmafEOTF eotf;
    vmaf_luminance_init_luma_range(&range, 10, VMAF_PIXEL_RANGE_LIMITED);
    vmaf_luminance_init_eotf(&eotf, "bt1886");
    uint16_t tvi[4];
    int weights[4] = {1, 2, 3, 4}, diffs[9];
    for (unsigned i = 0; i < 4; i++)
        tvi[i] = get_tvi_for_diff(i + 1, .019, 10, range, eotf) + 4;
    for (int i = 0; i < 9; i++) diffs[i] = i - 4;
    uint16_t vlt = get_vlt_luma(.06, range, eotf);
    unsigned base = vlt > 11 ? vlt - 11 : 0, bands = tvi[3] + 1 - base;
    uint16_t* histograms = calloc(w * bands, sizeof(*histograms));
    calculate_c_values(
        &picture, &mask_pic, values, histograms, window, 4, tvi, vlt, weights,
        diffs, w, h
    );
    if (window == 11) {
        printf("// Generated by vmaf_cambi_contrast_oracle.c; do not edit.\n");
        printf(
            "constexpr std::uint64_t kFilteredHash = %" PRIu64 "ULL;\n", hash
        );
    }
    if (window == 33)
        printf("// Generated by vmaf_cambi_contrast_oracle.c; do not edit.\n");
    printf("constexpr std::array<float, %u> kContrastOracle%u{\n", n, window);
    for (unsigned i = 0; i < n; ++i)
        printf("    %af,%s", values[i], i % 5 == 4 ? "\n" : " ");
    printf("\n};\n");
    free(image);
    free(mask);
    free(mode_scratch);
    free(values);
    free(histograms);
}
