VQM_TEST(TestVmafCambiPrepareGeometry) {
    using vqm::internal::VmafCambiPrepare;
    CHECK(VmafCambiPrepare::Pixels({216, 217}) == 216 * 217);
    CHECK(VmafCambiPrepare::MaskThreshold({216, 217}) == 13);
    CHECK(VmafCambiPrepare::MaskThreshold({1920, 1080}) == 21);
    CHECK_THROWS_AS(VmafCambiPrepare::Pixels({0, 217}), std::invalid_argument);
    CHECK_THROWS_AS(
        VmafCambiPrepare::Pixels({std::numeric_limits<std::size_t>::max(), 2}),
        std::invalid_argument
    );
}

VQM_TEST(TestVmafCambiPrepareAgainstLibvmaf) {
    if (!vqm::test::GpuAvailable()) return;
    using namespace vqm::internal;
    constexpr vqm::Size size{216, 217};
    constexpr std::size_t pixels = size.width * size.height;
    struct Case {
        unsigned depth, encoded_depth;
        std::uint64_t prepared_hash, mask_hash, mask_sum;
    };
    // Generated by tests/metrics/vmaf/cambi/vmaf_cambi_prepare_oracle.c using
    // the pinned libvmaf cambi_preprocessing and get_spatial_mask on every
    // pixel.
    constexpr std::array cases{
        Case{8, 8, 5144290443116617505ULL, 1163338352124148941ULL, 46860},
        Case{10, 10, 11688719102324403109ULL, 16044939188998491510ULL, 24967},
        Case{12, 12, 1865520309007490261ULL, 5792309745519440130ULL, 24701},
        Case{16, 16, 16666446602335472766ULL, 13813650447678828957ULL, 46872},
        Case{10, 8, 596859654052542129ULL, 7009387308966068159ULL, 23430},
    };
    constexpr VmafCambiPrepareBuffers buffers{0, pixels, 2 * pixels, 3 * pixels};
    VulkanRuntime::Config config;
    config.base_size = size;
    config.base_pixels = pixels;
    config.push_constant_size = VmafCambiPrepare::PushBytes();
    config.streaming = false;
    VulkanRuntime runtime(AcquireVulkanContext(), config);
    runtime.CreateArena(Bytes(4 * pixels));
    runtime.CreateStaging(Bytes(3 * pixels));
    runtime.CreateCommandObjects();
    runtime.CreateDescriptors(0, Bytes(4 * pixels));
    VmafCambiPrepare prepare(runtime);
    for (const auto& c : cases) {
        for (std::size_t y = 0; y < size.height; ++y) {
            for (std::size_t x = 0; x < size.width; ++x) {
                std::uint32_t v =
                    ((x / 9) * 31 + (y / 11) * 41 + (x / 57) * 7) % 256;
                if (c.depth > 8) {
                    const auto shift = c.depth - 8;
                    const std::uint32_t low =
                        ((x / 48 + y / 48) % 2)
                            ? static_cast<std::uint32_t>(
                                  (x * 3 + y * 5) & ((1u << shift) - 1u)
                              )
                            : 0;
                    v = (v << shift) | low;
                }
                runtime.staging_map()[y * size.width + x] =
                    std::ldexp(
                        static_cast<float>(v), 8 - static_cast<int>(c.depth)
                    ) -
                    128.0f;
            }
        }
        runtime.ResetCommandPool();
        runtime.BeginCommandBuffer();
        const std::array copies{
            VulkanRuntime::CopyRange{0, buffers.input, pixels}};
        runtime.RecordStagedCopies(copies);
        runtime.BindDescriptorSet();
        prepare.Record(size, c.depth, c.encoded_depth, buffers);
        runtime.RecordReadback(buffers.processed, pixels, pixels);
        runtime.RecordReadback(buffers.mask, 2 * pixels, pixels);
        runtime.EndCommandBuffer();
        runtime.SubmitAndWait();
        std::uint64_t prepared_hash = 14695981039346656037ULL;
        std::uint64_t mask_hash = 14695981039346656037ULL;
        std::uint64_t mask_sum = 0;
        for (std::size_t i = 0; i < pixels; ++i) {
            const auto value =
                static_cast<std::uint32_t>(runtime.staging_map()[pixels + i]);
            const auto mask = static_cast<std::uint32_t>(
                runtime.staging_map()[2 * pixels + i]
            );
            prepared_hash = (prepared_hash ^ value) * 1099511628211ULL;
            mask_hash = (mask_hash ^ mask) * 1099511628211ULL;
            mask_sum += mask;
        }
        CHECK(prepared_hash == c.prepared_hash);
        CHECK(mask_hash == c.mask_hash);
        CHECK(mask_sum == c.mask_sum);
    }
}

namespace {
using namespace vqm::internal;

// Independent integer conversion and separable spatial-mask oracle. Reuse one
// pipeline per geometry while covering both dispatch variants and bit depths.
class PrepareTileOracle {
public:
    explicit PrepareTileOracle(vqm::Size size)
        : size_(size),
          pixels_(size.width * size.height),
          buffers_{0, static_cast<std::uint32_t>(pixels_),
                   static_cast<std::uint32_t>(2 * pixels_),
                   static_cast<std::uint32_t>(3 * pixels_)},
          runtime_(AcquireVulkanContext(), Config(size)) {
        runtime_.CreateArena(Bytes(4 * pixels_));
        runtime_.CreateStaging(Bytes(4 * pixels_));
        runtime_.CreateCommandObjects();
        runtime_.CreateDescriptors(0, Bytes(4 * pixels_));
        prepare_.emplace(runtime_);
    }

    void Check(unsigned depth, unsigned encoded_depth) {
        std::vector<std::uint32_t> raw10(pixels_), converted(pixels_),
            derivative(pixels_), horizontal(pixels_);
        for (std::size_t y = 0; y < size_.height; ++y) {
            for (std::size_t x = 0; x < size_.width; ++x) {
                const auto at = y * size_.width + x;
                const auto shift = depth - 8u;
                const auto base = static_cast<std::uint32_t>(
                    ((x / 9) * 31 + (y / 11) * 41 + (x / 57) * 7) % 256
                );
                const auto low = static_cast<std::uint32_t>(
                    (x * 3 + y * 5) & ((1u << shift) - 1u)
                );
                const auto source = (base << shift) | low;
                runtime_.staging_map()[at] =
                    std::ldexp(
                        static_cast<float>(source), 8 - static_cast<int>(depth)
                    ) -
                    128.0f;
                if (depth < 10) {
                    raw10[at] = source << (10u - depth);
                } else {
                    const auto down = depth - 10u;
                    raw10[at] =
                        (source + (down ? 1u << (down - 1u) : 0u)) >> down;
                }
            }
        }
        for (std::size_t y = 0; y < size_.height; ++y) {
            for (std::size_t x = 0; x < size_.width; ++x) {
                const auto at = y * size_.width + x;
                auto value = raw10[at];
                if (encoded_depth < 10u) {
                    const bool has_x = x + 1 < size_.width;
                    const bool has_y = y + 1 < size_.height;
                    if (has_x && has_y)
                        value =
                            (value + raw10[at + 1] + raw10[at + size_.width] +
                             raw10[at + size_.width + 1]) >>
                            2u;
                    else if (has_x)
                        value = (value + raw10[at + 1]) >> 1u;
                    else if (has_y)
                        value = (value + raw10[at + size_.width]) >> 1u;
                }
                converted[at] = value;
            }
        }
        for (std::size_t y = 0; y < size_.height; ++y) {
            for (std::size_t x = 0; x < size_.width; ++x) {
                const auto at = y * size_.width + x;
                derivative[at] = (x + 1 == size_.width ||
                                  converted[at] == converted[at + 1]) &&
                                 (y + 1 == size_.height ||
                                  converted[at] == converted[at + size_.width]);
            }
        }
        for (std::size_t y = 0; y < size_.height; ++y) {
            for (std::size_t x = 0; x < size_.width; ++x) {
                unsigned total = 0;
                for (int dx = -3; dx <= 3; ++dx) {
                    const auto xx = static_cast<int>(x) + dx;
                    if (xx >= 0 && xx < static_cast<int>(size_.width))
                        total += derivative
                            [y * size_.width + static_cast<std::size_t>(xx)];
                }
                horizontal[y * size_.width + x] = total;
            }
        }
        runtime_.ResetCommandPool();
        runtime_.BeginCommandBuffer();
        const std::array copies{
            VulkanRuntime::CopyRange{0, buffers_.input, pixels_}};
        runtime_.RecordStagedCopies(copies);
        runtime_.BindDescriptorSet();
        prepare_->Record(size_, depth, encoded_depth, buffers_);
        runtime_.RecordReadback(buffers_.processed, pixels_, pixels_);
        runtime_.RecordReadback(buffers_.derivative, 2 * pixels_, pixels_);
        runtime_.RecordReadback(buffers_.mask, 3 * pixels_, pixels_);
        runtime_.EndCommandBuffer();
        runtime_.SubmitAndWait();
        std::size_t wrong_processed = 0, wrong_derivative = 0, wrong_mask = 0;
        const auto threshold = VmafCambiPrepare::MaskThreshold(size_);
        for (std::size_t y = 0; y < size_.height; ++y) {
            for (std::size_t x = 0; x < size_.width; ++x) {
                const auto at = y * size_.width + x;
                unsigned total = 0;
                for (int dy = -3; dy <= 3; ++dy) {
                    const auto yy = static_cast<int>(y) + dy;
                    if (yy >= 0 && yy < static_cast<int>(size_.height))
                        total += horizontal
                            [static_cast<std::size_t>(yy) * size_.width + x];
                }
                wrong_processed += runtime_.staging_map()[pixels_ + at] !=
                                   static_cast<float>(converted[at]);
                wrong_derivative += runtime_.staging_map()[2 * pixels_ + at] !=
                                    static_cast<float>(derivative[at]);
                wrong_mask += runtime_.staging_map()[3 * pixels_ + at] !=
                              static_cast<float>(total > threshold);
            }
        }
        CHECK(wrong_processed == 0);
        CHECK(wrong_derivative == 0);
        CHECK(wrong_mask == 0);
    }

private:
    static VulkanRuntime::Config Config(vqm::Size size) {
        VulkanRuntime::Config config;
        config.base_size = size;
        config.base_pixels = size.width * size.height;
        config.push_constant_size = VmafCambiPrepare::PushBytes();
        config.streaming = false;
        return config;
    }
    vqm::Size size_;
    std::size_t pixels_;
    VmafCambiPrepareBuffers buffers_;
    VulkanRuntime runtime_;
    std::optional<VmafCambiPrepare> prepare_;
};
}  // namespace

VQM_TEST(TestVmafCambiPrepareTileBoundaries) {
    if (!vqm::test::GpuAvailable()) return;
    for (auto size :
         {vqm::Size{1, 1}, vqm::Size{1, 17}, vqm::Size{17, 1}, vqm::Size{15, 16},
          vqm::Size{16, 17}, vqm::Size{17, 15}, vqm::Size{31, 33}}) {
        PrepareTileOracle oracle(size);
        for (const auto depth : {8u, 10u, 12u, 16u})
            for (std::uint32_t encoded_depth = 6; encoded_depth <= 16;
                 ++encoded_depth)
                oracle.Check(depth, encoded_depth);
    }
}

VQM_TEST(TestVmafCambiPrepareLargeOddTileBoundaries) {
    if (!vqm::test::GpuAvailable()) return;
    // Just above the cutoff, with partial tiles on both image edges.
    PrepareTileOracle oracle({3841, 2161});
    for (const auto [depth, encoded_depth] :
         {std::array{8u, 8u}, std::array{10u, 10u}})
        oracle.Check(depth, encoded_depth);
}
