"""Generate ColorVideoVDP base calibration and CSF tables from pinned originals.

Use the reference-only environment described in validation/cvvdp.md.
The generated tables are checked in; normal builds do not need Python/Torch or
an upstream checkout. Torch is used only to reproduce the original FP32 log
axes, including their rounding.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.dont_write_bytecode = True
DATA = ROOT / ".reference/ColorVideoVDP/pycvvdp/vvdp_data"
OUTPUT = ROOT / "src/metrics/cvvdp/cvvdp_model_data.inc"
PIN = "2a268bce8d56e2f3abde46df3927d8a633707a24"
HASHES = {
    "cvvdp_parameters.json":
    "ef4dedb44f11f33f509ea3d6d204bb23b03917259b8efbc077009ce53211762b",
    "csf_lut_weber_fixed_size.json":
    "df39c869c0c53a9a2cb757811ecaf4ce0d44b4151f5ff9590f5bfe1ede940c18",
    "color_spaces.json":
    "30ce6752d35672d97a9d7fb7286170915a2ddfe4307782693f9ee176ef9491d1",
    "display_models.json":
    "653979727e809fcd9e44424aff2615d54edde026d9feb17d8f07b7f0ff61b517",
}


def load_asset(name: str) -> dict[str, Any]:
    """Load a hash-verified upstream JSON object.

    :param name: Pinned data filename.
    :returns: The decoded JSON object.
    :raises ValueError: If the content differs from the inspected release.
    """
    content = (DATA / name).read_bytes()
    if hashlib.sha256(content).hexdigest() != HASHES[name]:
        raise ValueError(f"{name}: not the pinned ColorVideoVDP v0.5.7 asset")
    return json.loads(content)


def number(value: float) -> str:
    """Render a round-trip FP32 C++ literal.

    :param value: Original scalar.
    :returns: A float-suffixed literal.
    """
    rounded = struct.unpack("f", struct.pack("f", value))[0]
    text = format(rounded, ".9g")
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "f"


def emit_array(name: str, values: list[float]) -> list[str]:
    """Render one constexpr array.

    :param name: Original field or descriptive generated field name.
    :param values: Flattened scalar values.
    :returns: C++ declaration lines.
    """
    lines = [f"inline constexpr std::array<float, {len(values)}> {name} = {{"]
    for begin in range(0, len(values), 4):
        lines.append("    " + ", ".join(map(number, values[begin:begin + 4])) + ",")
    return [*lines, "};"]


def calibration_lines(parameters: dict[str, Any]) -> list[str]:
    """Render all numerical base-model calibration fields.

    :param parameters: Verified upstream parameters.
    :returns: C++ declaration lines.
    """
    lines = []
    for name, value in parameters.items():
        if isinstance(value, (float, int)):
            lines.append(f"inline constexpr float {name} = {number(value)};")
        elif isinstance(value, list):
            lines.extend(emit_array(name, value))
    return lines


def csf_lines(csf: dict[str, Any]) -> list[str]:
    """Render original FP32 logarithmic axes and log-sensitivity table.

    :param csf: Verified upstream CSF LUT.
    :returns: Arrays ordered channel, background luminance, spatial frequency.
    """
    import torch  # Optional reference-only dependency, never used by the core.

    log_luminance = torch.log10(torch.tensor(csf["L_bkg"], dtype=torch.float32))
    log_rho = torch.log10(torch.tensor(csf["rho"], dtype=torch.float32))
    values = [
        v for key in ("o0_c1", "o0_c2", "o0_c3", "o5_c1") for row in csf[key]
        for v in row
    ]
    return [
        *emit_array("log_luminance", log_luminance.tolist()),
        *emit_array("log_rho", log_rho.tolist()),
        "// [channel: Ys, rg, yv, Yt][background luminance][spatial frequency]",
        *emit_array("log_sensitivity", values)
    ]


def generate() -> str:
    """Generate the complete standalone include.

    :returns: C++ source text.
    """
    subprocess.run(
        [
            sys.executable,
            str(ROOT / "tools/fetch_references.py"), "--check", "--only",
            "ColorVideoVDP"
        ], check=True
    )
    parameters = load_asset("cvvdp_parameters.json")
    csf = load_asset("csf_lut_weber_fixed_size.json")
    for name in ("color_spaces.json", "display_models.json"):
        load_asset(name)
    lines = [
        "// Copyright (c) 2024 Graphics and Displays group.",
        "// MIT; see licenses/COLORVIDEOVDP-LICENSE.",
        "// Generated by tools/generate_cvvdp_tables.py; do not edit.",
        f"// Original ColorVideoVDP v0.5.7, commit {PIN}.",
        "// Numerical base model; no peer implementation data is used.", "",
        "#include <array>", "", "namespace vqm::internal::cvvdp_data {",
        "// clang-format off", *calibration_lines(parameters), *csf_lines(csf),
        *display_lines(), "// clang-format on",
        "}  // namespace vqm::internal::cvvdp_data", ""
    ]
    return "\n".join(lines)


def display_lines() -> list[str]:
    """Render original FP32 color matrices and exact preset angular sampling.

    :returns: Separate factor and composed RGB-to-DKL matrix declarations.
    """
    import torch

    sys.path.insert(0, str(ROOT / ".reference/ColorVideoVDP"))
    from pycvvdp.display_model import (  # noqa: N811
        LMS2006_to_DKLd65,
        XYZ_to_LMS2006,
        vvdp_display_geometry,
    )

    colors = load_asset("color_spaces.json")
    lms = torch.tensor(XYZ_to_LMS2006, dtype=torch.float32)
    dkl = torch.tensor(LMS2006_to_DKLd65, dtype=torch.float32)
    lines = [
        *emit_array("xyz_to_lms",
                    lms.flatten().tolist()),
        *emit_array("lms_to_dkl",
                    dkl.flatten().tolist())
    ]
    for name, key in (("rgb709", "sRGB"), ("rgb2020", "BT.2020-PQ"),
                      ("p3", "Display P3 Apple")):
        xyz = torch.tensor([colors[key][axis] for axis in ("RGB2X", "RGB2Y", "RGB2Z")])
        lines.extend(emit_array(name + "_to_xyz", xyz.flatten().tolist()))
        lines.extend(emit_array(name + "_to_dkl", (dkl @ lms @ xyz).flatten().tolist()))
    for name in ("standard_4k", "standard_fhd"):
        ppd = vvdp_display_geometry.load(name).get_ppd()
        lines.append(f"inline constexpr double {name}_ppd = {ppd:.17g};")
    return lines


def main() -> None:
    """Write generated data or verify the maintained copy."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not args.output.exists() or args.output.read_text() != text:
            raise SystemExit(f"{args.output}: generated CVVDP tables differ")
        print(f"{args.output}: pinned CVVDP tables match")
        return
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)


if __name__ == "__main__":
    main()
