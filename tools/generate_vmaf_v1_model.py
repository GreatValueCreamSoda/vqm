"""Generate v1 standard SDR 1080p predictor constants from the pinned model.

Verify the checked-in output with `python3 tools/generate_vmaf_v1_model.py --check`.
"""

import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = ROOT / ".reference/vmaf/model/vmaf_v1.0.16/vmaf_v1.0.16_3d0h.json"
DEFAULT_OUTPUT = ROOT / "src/metrics/vmaf/v1/vmaf_v1_model_data.inc"
MODEL_SHA256 = "e4cf8c147e1368b35497d772920bc92f98c1ad7853c1033d8a836947f427140e"
FEATURE_NAMES = [
    "Cambi_feature_cambi_score", "Speed_chroma_feature_speed_chroma_uv_score",
    "VMAF_integer_feature_adm3_score", "VMAF_integer_feature_motion3_score"
]


def number(value: float) -> str:
    """Render a finite double with round-trip precision.

    :param value: Model constant.
    :returns: Decimal literal for the generated C++ table.
    :raises ValueError: If the constant is not finite.
    """
    if not math.isfinite(value):
        raise ValueError("model values must be finite")
    return format(value, ".17g")


def _load_metadata(
    source: Path,
) -> tuple[list[float], list[float], dict[str, float], list[float], float, str]:
    content = source.read_bytes()
    if hashlib.sha256(content).hexdigest() != MODEL_SHA256:
        raise ValueError(f"{source}: not the pinned standard v1.0.16 SDR model")
    model = json.loads(content)["model_dict"]
    if model["feature_names"] != FEATURE_NAMES or model["norm_type"] != "linear_rescale":
        raise ValueError("unexpected VMAF model features or normalization")
    slopes, intercepts = model["slopes"], model["intercepts"]
    if len(slopes) != 5 or len(intercepts) != 5:
        raise ValueError("unexpected normalization size")
    transform, clip = model["score_transform"], model["score_clip"]
    if transform.get("enabled") is not True or len(clip) != 2:
        raise ValueError("unexpected score transform or clipping")
    correction = model["chroma_correction_parameter"]
    return slopes, intercepts, transform, clip, correction, model["model"]


def _vector_row(line: str) -> str:
    fields = line.split()
    coefficient = float(fields[0])
    vector = [0.0] * 4
    previous = 0
    for entry in fields[1:]:
        index_text, value = entry.split(":", 1)
        index = int(index_text)
        if index <= previous or index > 4:
            raise ValueError("invalid support vector index")
        vector[index - 1] = float(value)
        previous = index
    return "    {" + number(coefficient) + ", {" + ", ".join(
        map(number, vector)
    ) + "}},"


def _support_vectors(svm: str) -> tuple[str, list[str]]:
    header, points = svm.split("\nSV\n", 1)
    fields = dict(line.split(maxsplit=1) for line in header.splitlines())
    if fields != {"svm_type": "nu_svr", "kernel_type": "rbf", "gamma":
                  "0.035000000000000003", "nr_class": "2", "total_sv": "215", "rho":
                  "-1.2801585513962348"}:
        raise ValueError("unexpected VMAF SVM configuration")
    rows = [_vector_row(line) for line in points.splitlines()]
    if len(rows) != 215:
        raise ValueError("incorrect support vector count")
    return header, rows


def generate(source: Path) -> str:
    """Generate the C++ constants of the pinned SDR v1 predictor.

    :param source: Path to the original model file.
    :returns: Complete generated header text.
    :raises OSError: If the source model is unavailable.
    :raises ValueError: If the model differs from its pinned configuration.
    :raises KeyError: If a required model field is missing.
    """
    slopes, intercepts, transform, clip, correction, svm = _load_metadata(source)
    header, rows = _support_vectors(svm)
    return "\n".join(
        [
            "// Copyright (c) 2020 Netflix, Inc.",
            "// BSD-2-Clause-Patent; see licenses/NETFLIX-VMAF-LICENSE.",
            "// Generated by tools/generate_vmaf_v1_model.py from Netflix/vmaf",
            "// vmaf_v1.0.16_3d0h.json at 4611e47a7330cd342498dcc130e1008efbeab6e4.",
            "// SHA-256: " + MODEL_SHA256, "// Do not edit by hand.",
            "inline constexpr std::array<double, 5> kSlopes = {" +
            ", ".join(number(x) for x in slopes) + "};",
            "inline constexpr std::array<double, 5> kIntercepts = {" +
            ", ".join(number(x) for x in intercepts) + "};",
            "inline constexpr std::array<double, 3> kTransform = {" +
            ", ".join(number(transform[name]) for name in ("p0", "p1", "p2")) + "};",
            "inline constexpr std::array<double, 2> kClip = {" +
            ", ".join(number(x) for x in clip) + "};",
            "inline constexpr double kChromaCorrection = " + number(correction) + ";",
            "inline constexpr double kGamma = " + fields_gamma(header) + ";",
            "inline constexpr double kRho = -1.2801585513962348;",
            "inline constexpr std::array<SupportVector, 215> kSupportVectors = {{",
            *rows, "}};", "",
        ]
    )


def fields_gamma(header: str) -> str:
    """Render the RBF gamma from the libsvm header.

    :param header: Newline-delimited libsvm fields.
    :returns: Gamma formatted as a double literal.
    :raises KeyError: If gamma is missing from the header.
    :raises ValueError: If gamma cannot be represented as a finite double.
    """
    return number(
        float(dict(line.split(maxsplit=1) for line in header.splitlines())["gamma"])
    )


def main() -> None:
    """Write the generated model table or check the existing table.

    :raises SystemExit: If generation or verification fails.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        result = generate(args.model)
        if not args.check:
            args.output.write_text(result)
            print(f"wrote {args.output}")
            return
        if args.output.read_text() != result:
            raise ValueError(f"{args.output}: generated constants differ")
        print(f"{args.output}: matches pinned model")
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
